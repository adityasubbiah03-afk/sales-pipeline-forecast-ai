"""Turn the KPI summary into plain-English commentary for sales managers.

Two modes, chosen automatically:
  * LLM mode  - if ANTHROPIC_API_KEY is set and the `anthropic` package is installed, Claude
                writes the commentary from the KPI JSON.
  * Fallback  - otherwise a deterministic, rule-based writer produces the commentary, so the
                project always runs end to end with zero setup (and in CI).

Guardrail: the model receives only pre-computed numbers and is instructed to use no others.
"""
import json
import os

from src import config as C

SYSTEM_PROMPT = (
    "You are a sales-operations analyst writing a short commentary for sales managers. "
    "Use ONLY the numbers in the JSON provided; never calculate new figures or invent causes. "
    "Where the data cannot explain something, say so. Write in Australian English, plain and direct. "
    "Format: a one-sentence headline, then 4-6 bullets (performance, pipeline, forecast, risks), "
    "then a short 'Suggested actions' list of 2-3 items. Maximum 220 words. Amounts are AUD."
)


def _m(x):
    return f"${x / 1e6:,.2f}M"


def rule_based_commentary(k: dict) -> str:
    r, w, p, f = k["revenue"], k["win_rate"], k["pipeline"], k["forecast_next_month"]
    direction = "ahead of" if r["last_month_vs_target_pct"] >= 0 else "behind"
    lines = [
        f"**Headline:** {k['last_full_month']} won revenue was {_m(r['last_month_won'])}, "
        f"{abs(r['last_month_vs_target_pct']):.1f}% {direction} target.", "",
        f"- **Performance:** Last 3 months won {_m(r['last_3m_won'])} ({r['last_3m_change_pct']:+.1f}% vs the prior 3 months). "
        f"Win rate is {w['last_3m_pct']:.1f}% (prior: {w['prior_3m_pct']:.1f}%); gross margin {k['gross_margin_pct']['last_3m']:.1f}%.",
        f"- **Where we win:** {w['highest_industry_last_3m']['industry']} converts best ({w['highest_industry_last_3m']['pct']:.0f}%); "
        f"{w['lowest_industry_last_3m']['industry']} converts worst ({w['lowest_industry_last_3m']['pct']:.0f}%).",
        f"- **Pipeline:** {p['open_deals']} open deals worth {_m(p['open_value'])}; "
        f"{p['stale_or_overdue_pct']:.1f}% of that value is stale or overdue and excluded from the forecast.",
        f"- **Forecast ({f['period']}):** {_m(f['statistical_forecast'])} (80% range {_m(f['range_80'][0])} to {_m(f['range_80'][1])}) "
        f"versus a {_m(f['target'])} target; weighted active pipeline for that month is {_m(f['weighted_pipeline'])}.",
    ]
    if k["anomalies"]:
        lines.append("- **Flags:** " + " ".join(a["detail"] for a in k["anomalies"]))
    actions = []
    if p["stale_or_overdue_pct"] > 15:
        actions.append("Ask reps to re-qualify or close out stale and overdue deals this week.")
    if p["implied_win_rate_pct"] - p["historical_value_win_rate_pct"] > 10:
        actions.append("Recalibrate stage probabilities to historical conversion before using the weighted pipeline in forecast calls.")
    if f["statistical_forecast"] < f["target"]:
        actions.append("Review whether pipeline creation is sufficient to close the gap to target.")
    actions.append("Investigate the lowest-converting industry for qualification or pricing issues.")
    lines += ["", "**Suggested actions**"] + [f"- {a}" for a in actions[:3]]
    return "\n".join(lines)


def llm_commentary(k: dict):
    """Return commentary text from Claude, or None if the API is unavailable."""
    if not os.environ.get("ANTHROPIC_API_KEY"):
        return None
    try:
        from anthropic import Anthropic
        model = os.environ.get("ANTHROPIC_MODEL", C.DEFAULT_LLM_MODEL)
        msg = Anthropic().messages.create(
            model=model, max_tokens=700, system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": "KPI summary (JSON):\n" + json.dumps(k, indent=2)}],
        )
        return msg.content[0].text.strip(), model
    except Exception as exc:  # network error, bad key, package missing...
        print(f"[commentary] LLM call failed ({type(exc).__name__}); using rule-based commentary instead.")
        return None


def generate_commentary(k: dict, use_llm: bool = True) -> str:
    result = llm_commentary(k) if use_llm else None
    if result:
        text, model = result
        source = f"Generated by LLM ({model}) from the KPI summary"
    else:
        text, source = rule_based_commentary(k), "Generated by the built-in rule-based writer (no API key used)"
    return f"# Sales Performance Commentary - {k['as_of']}\n\n_{source}. All figures are computed in Python; see `reports/kpi_summary.json`._\n\n{text}\n"
